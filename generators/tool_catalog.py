def _sid(*parts) -> int:
    """稳定 slug 后缀（zlib.crc32；**不能用内置 hash()** —— 跨进程随机化，
    会让同一工具每次生成的 URL 都不一样，内链与 sitemap 全部失效）。"""
    import zlib
    key = "|".join(str(p) for p in parts).encode("utf-8")
    return zlib.crc32(key) % 10**6


def unit_pairs(cat: str, units: list) -> list[tuple[int, int]]:
    """
    取该类别里的换算组合。

    包含**全部有序对**（"厘米转英寸" 与 "英寸转厘米" 都是真实高频需求，
    不是凑数 —— 两者的使用场景、默认值和内容都不同）。
    排序：基准单位优先，其次按"最常用单位优先"。
    """
    n = len(units)
    base_first = [0] + [i for i in range(1, n)]
    pairs: list[tuple[int, int]] = []
    for a in base_first:
        for b in range(n):
            if a == b:
                continue
            pairs.append((a, b))
    return pairs[:PAIRS_PER_CAT]


